def generate_faq_jsonld():
    entities = []
    for item in FAQ_ITEMS:
        entities.append({
            "@type": "Question",
            "name": item["q"],
            "acceptedAnswer": {
                "@type": "Answer",
                "text": item["a"]
            }
        })
    faq_schema = {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        "mainEntity": entities
    }
    return json.dumps(faq_schema, ensure_ascii=False, indent=2)

